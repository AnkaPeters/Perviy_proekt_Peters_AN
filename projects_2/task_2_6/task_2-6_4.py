vybor = input("Введите желаемое направление движения: ").strip().upper()

if vybor == 'НАЛЕВО':
    print("Коня потеряешь")
elif vybor == 'НАПРАВО':
    print("Жизнь потеряешь")
elif vybor == 'ПРЯМО':
    print("Жив будешь, да себя позабудешь")
else:
    print("Да познаешь сам последствия")
